#!/usr/bin/env python3
"""
Parity of libnest.edf.pairing with the C implementation (W-BSK hpc-engine,
bsk/bsk_functional.c: g_Delta_NM_ref, g_Delta_SM_ref, g_Delta_n_ref, g_Delta_p_ref).

The C values are stored in tests/golden/c_pairing.json, generated by
``python -m tests.golden.make_c_pairing /path/to/W-BSK --write``, so the test runs
without the C code.

The two codes regularize differently, and the test compares the formulas only:

* the asymmetry: C uses delta = eta/rho in the Chamel scheme and eta/(rho + 1e-8) in
  Eqs. 3 and 6; the test patches DENSEPSILON of libnest.edf.pairing to the same value;
* closed gaps: C returns 1e-8 MeV, libnest NUMZERO (atol 1e-8 MeV); in Eq. 6 C also
  floors both reference gaps at 1e-8 MeV before their ratio (atol 1e-6 MeV, see
  TODO_edf.md section 5);
* Eq. 6 only: C takes Delta_NeuM(rho/2) at the bare rho, libnest at rho + DENSEPSILON
  (which keeps rho = 0 finite); with the patched DENSEPSILON this shifts the gap by a
  relative 2 eps/rho at most.
"""
import json
import os
import unittest
from unittest import mock

import numpy as np

from libnest.edf import pairing

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "golden", "c_pairing.json")

#: per scheme: DENSEPSILON of C in delta [fm^-3], atol [MeV], and whether the Eq. 6
#: rho/2 regularization applies
C_REGULARIZATION = {
    "chamel2009": (0.0, 1e-8, False),
    "bskg3_eq3": (1e-8, 1e-8, False),
    "bskg4_eq6": (1e-8, 1e-6, True),
}
RTOL = 1e-12


class TestParityWithC(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        with open(DATA) as f:
            cls.c = json.load(f)
        cls.inputs = {k: np.array(v) for k, v in cls.c["inputs"].items()}
        cls.gaps = pairing.GAP_MODELS["cao2006"]

    def test_every_c_scheme_is_covered(self):
        self.assertEqual(set(self.c["schemes"]), set(C_REGULARIZATION))
        self.assertTrue(set(C_REGULARIZATION) <= set(pairing.SCHEMES))

    def test_gap_model(self):
        kF = self.inputs["kF"]
        for name, gap in (("neutron_matter", self.gaps.neutron_matter_kf),
                          ("symmetric_matter", self.gaps.symmetric_matter_kf)):
            with self.subTest(gap=name):
                np.testing.assert_allclose(gap(kF), self.c["gap_model"][name],
                                           rtol=RTOL, atol=1e-8)

    def test_interpolation_schemes(self):
        rho_n, rho_p = self.inputs["rho_n"], self.inputs["rho_p"]
        rho = rho_n + rho_p
        for name, (epsilon, atol, half_density_shift) in C_REGULARIZATION.items():
            scheme = pairing.SCHEMES[name]
            rtol = RTOL + (2.*epsilon/rho if half_density_shift else 0.)
            with mock.patch.object(pairing, "DENSEPSILON", epsilon):
                computed = {"neutron": scheme(self.gaps, rho_n, rho_p),
                            "proton": scheme(self.gaps, rho_p, rho_n)}
            for q, values in computed.items():
                with self.subTest(scheme=name, q=q):
                    expected = np.array(self.c["schemes"][name][q])
                    excess = np.abs(values - expected) - (atol + rtol*np.abs(expected))
                    worst = int(np.argmax(excess))
                    self.assertLessEqual(
                        excess[worst], 0.,
                        "rho_n={}, rho_p={}: libnest {} vs C {}".format(
                            rho_n[worst], rho_p[worst], values[worst], expected[worst]))


if __name__ == "__main__":
    unittest.main()
