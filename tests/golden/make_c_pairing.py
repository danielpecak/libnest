"""
Generates ``tests/golden/c_pairing.json``: the reference pairing gaps of the C
implementation (W-BSK hpc-engine, ``bsk/bsk_functional.c``) for every interpolation
scheme, compared with :mod:`libnest.edf.pairing` by ``tests/test_pairing_c.py``.

Usage (from the repository root; needs gcc and a W-BSK checkout, i.e. the directory
that contains ``hpc-engine/`` and ``extensions/``):

    python -m tests.golden.make_c_pairing /path/to/W-BSK            # report differences
    python -m tests.golden.make_c_pairing /path/to/W-BSK --write    # (re)write the file

The W-BSK path can also come from ``$WBSK``. The functional is compiled the same way
as W-BSK's ``testsuite/bsk-functional-checks``: BSK=31, NUCLEAR_MATTER, with
PAIRING_INTERPOLATION forced to each scheme (the reference gaps do not depend on the
Skyrme parameters).
"""
import argparse
import datetime
import json
import os
import subprocess
import tempfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PATH = os.path.join(HERE, "c_pairing.json")

# libnest scheme name -> PAIRING_INTERPOLATION id of bsk_constants.h
C_SCHEMES = {"chamel2009": 1, "bskg4_eq6": 2, "bskg3_eq3": 3}

DRIVER = r"""
#include <stdio.h>
#include <math.h>
double bsk_runtime_dx=1.0, bsk_runtime_dy=1.0, bsk_runtime_dz=1.0;
#define BSKEXTERNC
#include "bsk_settings.h"
#include "bsk_functional.h"

/* stdin: lines "g kF" (gap model) or "s rho_n rho_p" (scheme); stdout: two gaps */
int main(void)
{
    char kind;
    double a, b;
    while (scanf(" %c", &kind) == 1) {
        if (kind == 'g' && scanf("%lf", &a) == 1)
            printf("%.17g %.17g\n", Delta_NM_ref(a), Delta_SM_ref(a));
        else if (kind == 's' && scanf("%lf %lf", &a, &b) == 2)
            printf("%.17g %.17g\n", Delta_n_ref(a, b), Delta_p_ref(a, b));
        else
            return 1;
    }
    return 0;
}
"""


def make_inputs():
    """Total density x proton fraction (rho > 0: the C Chamel scheme divides by rho),
    with points on both sides of the cutoffs (see tests/golden/spec.py), and a kF grid
    across both gap cutoffs (1.31 and 1.38 fm^-1)."""
    rho_grid = [1e-4, 1e-3, 0.005, 0.01, 0.02, 0.04, 0.06, 0.08, 0.0885, 0.089, 0.1,
                0.12, 0.151, 0.152, 0.16, 0.177, 0.178, 0.2, 0.3]
    yp_grid = [0., 0.02, 0.1, 0.3, 0.45, 0.5, 0.55, 0.7, 0.9, 0.98, 1.]
    rho, yp = (a.ravel() for a in np.meshgrid(rho_grid, yp_grid, indexing="ij"))
    kF = np.concatenate([np.linspace(0., 1.6, 33), [1.305, 1.315, 1.375, 1.385]])
    return {"rho_n": (1. - yp)*rho, "rho_p": yp*rho, "kF": np.sort(kF)}


def _run(cmd, **kwargs):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kwargs).stdout


def _evaluate(wbsk, scheme_id, stdin, workdir):
    engine = os.path.join(wbsk, "hpc-engine")
    exe = os.path.join(workdir, "pairing-{}.exe".format(scheme_id))
    driver = os.path.join(workdir, "driver.c")
    with open(driver, "w") as f:
        f.write(DRIVER)
    _run(["gcc", "-std=gnu99", "-O2", "-DBSK=31", "-DPURE_NEUTRON=1", "-DNUCLEAR_MATTER=2",
          "-DMATTER_MODE=NUCLEAR_MATTER", "-DPAIRING_INTERPOLATION={}".format(scheme_id),
          "-include", os.path.join(wbsk, "extensions", "bsk-edf-energy",
                                   "bsk_edf_runtime_dx.h"),
          "-I" + os.path.join(engine, "bsk"), "-I" + engine, "-o", exe, driver,
          os.path.join(engine, "bsk", "bsk_functional.c"), "-lm"])
    out = np.loadtxt(_run([exe], input=stdin).splitlines(), ndmin=2)
    return out[:, 0], out[:, 1]


def _source(wbsk):
    try:
        commit = _run(["git", "rev-parse", "--short", "HEAD"], cwd=wbsk).strip()
        dirty = _run(["git", "status", "--porcelain", "--", "hpc-engine/bsk"], cwd=wbsk)
        return commit + ("+local changes in hpc-engine/bsk" if dirty.strip() else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def generate(wbsk):
    inputs = make_inputs()
    gap_stdin = "".join("g {!r}\n".format(float(k)) for k in inputs["kF"])
    scheme_stdin = "".join("s {!r} {!r}\n".format(float(n), float(p))
                           for n, p in zip(inputs["rho_n"], inputs["rho_p"]))
    data = {
        "about": "Reference pairing gaps of W-BSK hpc-engine bsk/bsk_functional.c "
                 "(g_Delta_NM_ref, g_Delta_SM_ref, g_Delta_n_ref, g_Delta_p_ref). "
                 "Generated by tests/golden/make_c_pairing.py - do not edit by hand.",
        "generated": {"date": datetime.date.today().isoformat(),
                      "wbsk_commit": _source(wbsk)},
        "inputs": {k: v.tolist() for k, v in inputs.items()},
        "schemes": {},
    }
    with tempfile.TemporaryDirectory() as workdir:
        for name, scheme_id in C_SCHEMES.items():
            if "gap_model" not in data:
                nm, sm = _evaluate(wbsk, scheme_id, gap_stdin, workdir)
                data["gap_model"] = {"neutron_matter": nm.tolist(),
                                     "symmetric_matter": sm.tolist()}
            dn, dp = _evaluate(wbsk, scheme_id, scheme_stdin, workdir)
            data["schemes"][name] = {"neutron": dn.tolist(), "proton": dp.tolist()}
    return data


def _max_differences(old, new):
    """Largest absolute change per stored array (None if missing or reshaped)."""
    def arrays(d):
        for k in ("rho_n", "rho_p", "kF"):
            yield ("inputs", k), d["inputs"][k]
        for k, v in d.get("gap_model", {}).items():
            yield ("gap_model", k), v
        for s, gaps in d.get("schemes", {}).items():
            for q, v in gaps.items():
                yield (s, q), v
    stored = dict(arrays(old))
    for key, value in arrays(new):
        o = stored.get(key)
        same_shape = o is not None and len(o) == len(value)
        yield key, (float(np.max(np.abs(np.subtract(o, value)))) if same_shape else None)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("wbsk", nargs="?", default=os.environ.get("WBSK"),
                        help="W-BSK checkout (default: $WBSK)")
    parser.add_argument("--write", action="store_true", help="(re)write " + PATH)
    args = parser.parse_args()
    if not args.wbsk:
        parser.error("give the W-BSK path or set $WBSK")
    new = generate(os.path.abspath(args.wbsk))
    if args.write:
        with open(PATH, "w") as f:
            json.dump(new, f, indent=1)
            f.write("\n")
        print("Written", PATH)
        return
    if not os.path.exists(PATH):
        print("No", PATH, "yet; nothing written (use --write).")
        return
    with open(PATH) as f:
        old = json.load(f)
    for key, diff in _max_differences(old, new):
        print("{:32s} {}".format("/".join(key), "new" if diff is None else
                                 "max |change| = {:.3g}".format(diff)))
    print("Nothing written (use --write).")


if __name__ == "__main__":
    main()
